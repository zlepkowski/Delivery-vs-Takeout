#!/usr/bin/env python3
"""Build src/data/zips.js: US ZIP centroids in the BUILD.md section 2 packed format.

Usage (from the repo root):
    python3 -I tools/build-zips.py --as-of 2026-11-12 \
        --cache <scratch dir> --out src/data/zips.js [--refresh]

Source: midwire/free_zipcode_data, all_us_zipcodes.csv (public domain, GitHub).
The raw download goes into --cache (never into the repo). If the cached copy is
already there it is reused, so a re-run reproduces the output byte for byte;
pass --refresh to download again.

Filters (BUILD.md section 2): skip rows whose lat/lon don't parse or are out of
range, (0, 0) rows, and rows whose state isn't exactly two letters. City is the
trimmed, title-cased name, indexed in first-seen order.

Output: POD.data.ZIP_CITIES (array of city names) and POD.data.ZIP_PACKED
(a string of records "zip,lat*1000,lon*1000,cityIndex,ST" joined by ";").
Nothing from the downloaded file is executed.
"""

import argparse
import csv
import hashlib
import json
import os
import re
import sys
import urllib.request

SOURCE_URL = "https://raw.githubusercontent.com/midwire/free_zipcode_data/master/all_us_zipcodes.csv"
SOURCE_NAME = "midwire/free_zipcode_data"
CACHE_NAME = "all_us_zipcodes.csv"
USER_AGENT = "pod-data-research/1.0"
TIMEOUT_S = 60


def fetch(cache_dir, refresh):
    """Returns the path of the cached CSV, downloading it first if needed."""
    os.makedirs(cache_dir, exist_ok=True)
    path = os.path.join(cache_dir, CACHE_NAME)
    if os.path.exists(path) and not refresh:
        return path
    req = urllib.request.Request(SOURCE_URL, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=TIMEOUT_S) as resp:
        data = resp.read()
    if not data:
        sys.exit("empty download from " + SOURCE_URL)
    tmp = path + ".part"
    with open(tmp, "wb") as f:
        f.write(data)
    os.replace(tmp, path)
    return path


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def build(csv_path):
    """Returns (cities, records, stats) from the raw CSV."""
    cities, city_index, records = [], {}, []
    stats = {"rows": 0, "bad_coords": 0, "zero_coords": 0, "bad_state": 0}
    with open(csv_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            stats["rows"] += 1
            try:
                la = float(row["lat"])
                lo = float(row["lon"])
            except (TypeError, ValueError):
                stats["bad_coords"] += 1
                continue
            if not (-90 < la < 90 and -180 < lo < 180):
                stats["bad_coords"] += 1
                continue
            if la == 0 and lo == 0:
                stats["zero_coords"] += 1
                continue
            state = (row["state"] or "").strip()
            if len(state) != 2 or not state.isalpha():
                stats["bad_state"] += 1
                continue
            city = row["city"].strip().title()
            if city not in city_index:
                city_index[city] = len(cities)
                cities.append(city)
            records.append("%s,%d,%d,%d,%s" % (
                row["code"].strip(),
                round(la * 1000),
                round(lo * 1000),
                city_index[city],
                state.upper(),
            ))
    return cities, records, stats


def render(cities, records, as_of, input_sha):
    header = (
        "/*\n"
        " * ZIP centroids: 5-digit US ZIP codes with lat/lon, city and state (BUILD.md section 2).\n"
        " * Source:  %s %s\n"
        " * As of:   %s\n"
        " * Method:  generated by tools/build-zips.py (input sha256 %s)\n"
        " * Nulls:   none\n"
        " * Est:     none\n"
        " */\n" % (SOURCE_NAME, SOURCE_URL, as_of, input_sha)
    )
    cities_js = json.dumps(cities, separators=(",", ":"), ensure_ascii=True)
    packed_js = json.dumps(";".join(records), separators=(",", ":"), ensure_ascii=True)
    body = (
        "(function (root) {\n"
        "  \"use strict\";\n"
        "  var D = root.POD.data;\n"
        "  D.ZIP_CITIES = %s;\n"
        "  D.ZIP_PACKED = %s;\n"
        "})(typeof window !== \"undefined\" ? window : this);\n"
    ) % (cities_js, packed_js)
    return header + body


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--as-of", required=True, help="YYYY-MM-DD, written into the header")
    ap.add_argument("--cache", required=True, help="scratch directory for the raw download")
    ap.add_argument("--out", required=True, help="output path, e.g. src/data/zips.js")
    ap.add_argument("--refresh", action="store_true", help="download again even if cached")
    args = ap.parse_args()

    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.as_of):
        sys.exit("--as-of must be YYYY-MM-DD")

    csv_path = fetch(args.cache, args.refresh)
    input_sha = sha256_of(csv_path)
    cities, records, stats = build(csv_path)

    zips = [r.split(",", 1)[0] for r in records]
    if len(set(zips)) != len(zips):
        sys.exit("duplicate ZIP codes in source; refusing to write")

    text = render(cities, records, args.as_of, input_sha)
    out_dir = os.path.dirname(os.path.abspath(args.out))
    os.makedirs(out_dir, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)

    print("source rows: %d" % stats["rows"])
    print("skipped: bad coords %d, (0,0) %d, bad state %d" % (
        stats["bad_coords"], stats["zero_coords"], stats["bad_state"]))
    print("zips: %d" % len(records))
    print("cities: %d" % len(cities))
    print("input sha256: %s" % input_sha)
    print("wrote %s (%d bytes)" % (args.out, len(text.encode("utf-8"))))


if __name__ == "__main__":
    main()
